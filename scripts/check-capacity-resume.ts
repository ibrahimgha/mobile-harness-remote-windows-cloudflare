import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { CodexRunner, isModelCapacityError } from "../server/codexRunner.js";
import type { CodexRunJob } from "../server/types.js";

type Internals = {
  queue: Array<{job: CodexRunJob; text: string}>;
  runningChatIds: Set<string>;
  emit: (job: CodexRunJob, event: "failed" | "stopped") => void;
  processNext: () => void;
  runJob: (job: CodexRunJob, text: string) => Promise<void>;
};
const root = mkdtempSync(path.join(os.tmpdir(), "capacity-resume-"));
const originalNow = Date.now;
let now = originalNow();
Date.now = () => now;
try {
  assert.ok(isModelCapacityError('Selected model is at capacity. Please try a different model.'));
  assert.ok(isModelCapacityError('{"message":"Selected model is at capacity. Please try a different model."}'));
  assert.equal(isModelCapacityError('Model not supported'), false);
  const journal = path.join(root, "journal.json");
  const runner = new CodexRunner({statePath: journal});
  const internal = runner as unknown as Internals;
  internal.runningChatIds.add("chat");
  const settings = {model:"gpt-6.1-sol", reasoningEffort:"medium" as const, speed:"priority" as const, updatedAt:new Date().toISOString()};
  const failed = runner.enqueue({chatId:"chat", projectPath:root, text:"original", promptPreview:"original", promptHash:"original", textLength:8, settings});
  internal.queue.splice(0);
  failed.status="failed";
  failed.finishedAt=new Date(now).toISOString();
  failed.message="Selected model is at capacity. Please try a different model.";
  internal.emit(failed,"failed");
  internal.emit(failed,"failed");
  assert.equal(internal.queue.length,1,"duplicate failure events schedule exactly one resume");
  const retry=internal.queue[0];
  assert.equal(retry.text,"resume");
  assert.equal(Date.parse(retry.job.notBefore!),now+300000);
  assert.deepEqual(retry.job.settings,settings);
  assert.equal(retry.job.capacityRetryOfJobId,failed.id);
  assert.equal(retry.job.capacityRetryFailedAt,failed.finishedAt);
  const restored=new CodexRunner({statePath:journal});
  const recovered=restored as unknown as Internals;
  assert.equal(recovered.queue[0].job.notBefore,retry.job.notBefore,"deadline survives reboot");
  assert.deepEqual(recovered.queue[0].job.settings,settings);
  const starts: string[]=[];
  recovered.runJob=async(job,text)=>{starts.push(text);job.status="completed";};
  recovered.processNext();
  assert.equal(starts.length,0);
  now+=299999;
  recovered.processNext();
  assert.equal(starts.length,0,"never resume before five minutes");
  now+=1;
  recovered.processNext();
  assert.deepEqual(starts,["resume"]);
  await new Promise(resolve=>setImmediate(resolve));
  // Test the real external-activity guard, including persisted retry recovery.
  let scannedStart=failed.finishedAt!;
  const guarded=new CodexRunner({statePath:journal,getExternalActiveRuns:async()=>[{chatId:"chat",startedAt:scannedStart}]});
  const guardedInternal=guarded as unknown as Internals;
  const guardedStarts:string[]=[];
  guardedInternal.runJob=async(job,text)=>{guardedStarts.push(text);job.status="completed";};
  // A genuinely newer writer must remain protected even after the deadline.
  scannedStart=new Date(Date.parse(failed.finishedAt!)+1).toISOString();
  await guarded.refreshExternalActivity(true);
  assert.equal(guardedStarts.length,0,"newer external writer must block retry");
  scannedStart=failed.finishedAt!;
  await guarded.refreshExternalActivity(true);
  assert.deepEqual(guardedStarts,["resume"],"stale failed writer must not strand an overdue restored retry");
  await new Promise(resolve=>setImmediate(resolve));
  const job=retry.job;
  internal.queue.splice(0);
  job.status="failed";job.message=failed.message;
  internal.emit(job,"failed");
  assert.equal(internal.queue.length,1,"each repeated capacity failure schedules a fresh resume");
  assert.equal(Date.parse(internal.queue[0].job.notBefore!),now+300000);
  runner.cancelQueuedJob(internal.queue[0].job.id);
  assert.equal(internal.queue.length,0,"retry is cancellable");
  failed.id="other-error";failed.message="Model not supported";
  internal.emit(failed,"failed");
  assert.equal(internal.queue.length,0,"unrelated failures never retry");
  // Exercise the production interval, not just manual calls to processNext.
  const ticking = new CodexRunner({statePath:null});
  const clocked = ticking as unknown as Internals;
  const automaticStarts: string[] = [];
  clocked.runJob = async (job,text) => { automaticStarts.push(text); job.status="completed"; };
  clocked.runningChatIds.add("timer-chat");
  const automatic = ticking.enqueue({chatId:"timer-chat",projectPath:root,text:"resume",promptPreview:"resume",promptHash:"timer-fixture",textLength:6,settings});
  automatic.notBefore = new Date(now+1000).toISOString();
  clocked.runningChatIds.delete("timer-chat");
  ticking.start();
  now += 999;
  await new Promise(resolve=>setTimeout(resolve,1100));
  assert.equal(automaticStarts.length,0,"live scheduler does not send early");
  now += 1;
  await new Promise(resolve=>setTimeout(resolve,1100));
  assert.deepEqual(automaticStarts,["resume"],"live scheduler starts the existing retry at its deadline without X or a new prompt");
  assert.deepEqual(automatic.settings,settings);
  console.log("PASS: capacity-only resume, exact five-minute deadline, settings, deduplication, reboot persistence, repeated failure and cancellation.");
} finally {
  Date.now=originalNow;
  rmSync(root,{recursive:true,force:true});
}
