type BubbleMessage = { role: string; kind?: string; text: string };

const attachmentHeading = "Attached files saved on the target laptop:";
const attachmentFooter = "Use these local file paths when working on this request.";

/** Display-only projection: retain the original prompt for the runner, copying, and queue edits. */
export function messageBubbleContent(message: BubbleMessage): { text: string; attachmentCount: number } {
  const unchanged = { text: message.text, attachmentCount: 0 };
  if (message.role !== "user" || message.kind === "voice_note") return unchanged;

  // Only collapse the complete suffix generated by promptWithUploadedFiles. Ordinary
  // paths, assistant file links, and quoted/incomplete attachment instructions stay visible.
  const start = message.text.lastIndexOf(attachmentHeading);
  if (start < 0) return unchanged;
  const prefix = message.text.slice(0, start);
  if (prefix && !/\r?\n\r?\n$/.test(prefix)) return unchanged;
  const lines = message.text.slice(start).trimEnd().split(/\r?\n/);
  if (lines[0] !== attachmentHeading || lines.at(-1) !== attachmentFooter || lines.at(-2) !== "") return unchanged;

  const fileLines = lines.slice(1, -2);
  if (!fileLines.length || fileLines.length % 2 !== 0) return unchanged;
  for (let index = 0; index < fileLines.length; index += 2) {
    const entry = /^(\d+)\. .+ \(\d+(?:\.\d+)? (?:B|KB|MB|GB|TB)\)$/.exec(fileLines[index]);
    if (!entry || Number(entry[1]) !== index / 2 + 1) return unchanged;
    if (!/^ {3}(?:[A-Za-z]:[\\/]|\\\\|\/).+/.test(fileLines[index + 1])) return unchanged;
  }

  return { text: prefix.trimEnd(), attachmentCount: fileLines.length / 2 };
}
